"""### Bayes Theorem

**Why do we need Bayesian inference?**

In general, statistical inference is the process of determining properties of a model/distribution, given some data. Bayesian inference can be seen as the Bayesian counterpart to frequentist inference. In Frequentist inference, there is usually the notion of some true, unknown parameter which is a constant, and point estimates are inferred from data. Contrarily, Bayesian inference treats the model parameters as random variables and usually aims to deduce probabilistic statements about the distribution of parameters.

**Terminology**

The basic terms related to Bayesian inference are as follows:

- **Prior:** The probability distribution that would express one's beliefs about an uncertain quantity before some evidence is taken into account.
- **Posterior:** In Bayesian statistics, it is the revised or updated probability of an event occurring after taking into consideration new information.

### Naive Bayes Classifiers

Naive Bayes classifiers are built on Bayes' rule.
We are trying to use Bayes' theorem to classify data (can be images, text, speech, or any other form of data). We're interested in finding the probability of a label given the observations made, which we can write as $P(L~|~{D})$.
Bayes's theorem tells us how to express this in terms of quantities we can compute more directly:

$$
P(L~|~{
m D}) = \frac{P({\rm D}~|~L)P(L)}{P({\rm D})}
$$

If we have two classes (two labels), let them be denoted by $L_1$ and $L_2$—then one way to make this decision is to compute the ratio of the posterior probabilities for each label:

$$\frac{P(L_1~|~{\rm D})}{P(L_2~|~{\rm D})} = \frac{P({\rm D}~|~L_1)}{P({\rm D}~|~L_2)}\frac{P(L_1)}{P(L_2)}
$$

All we need now is some model by which we can compute $P({\rm D}~|~L_i)$ for each label.
Such a model is called a *generative model* because it specifies the hypothetical random process that generates the data.
Specifying this generative model for each label is the main piece of the training of such a Bayesian classifier.
The general version of such a training step is a very difficult task, but we can make it simpler through a "Naive" assumption that each label is associated with a specific distribution (often a Gaussian).

Let us now check how to use a Naive Bayes classifier. We first load the IRIS dataset. Please note that the same dataset will also be used to train a decision tree in the next part of this assignment.
"""

# Preparing the data into X (predictor) and Y (target).
iris = datasets.load_iris()

# Considering two features, the sepal length and width.
