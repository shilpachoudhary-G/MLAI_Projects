"""#### How Decision Tree Makes Predictions

In the above example, we see how the Decision Tree makes predictions. To classify a flower, at depth 0, at the top (root node), this node asks the condition whether the flower’s sepal length $\leq$ 2.45 cm. If it is, then we move down to the root’s left child node (depth 1, left). Here, it's a leaf node (meaning it does not have any child nodes), so it does not ask any questions: you can simply look at the predicted class for that node and the Decision Tree predicts that the flower is an Iris-Setosa (class=setosa).

Now, in another case, when the sepal length of a flower is $\geq$ 2.45cm, we then move down to the right child node (depth 1, right), which is not a leaf node, and ask if sepal width is $\leq$ 1.75cm. If it is, then the flower is Iris-Versicolor (depth 2, left). If not, it is surely Iris-Virginica (depth 2, right).

On each node, the `samples` represent the number of training instances. For example, 54 samples have sepal length $\geq$ 2.45cm and sepal width $\leq$ 1.75cm (depth 2, left). The node's `values` show how many training instances of each class this node applies. For example, at depth 2, right, applies 0 to Iris-Setosa, 1 to Iris-Versicolor, and 45 to Iris-Virginica.

At last, the `gini-impurity` measures the node's impurity. If a node is `pure` (gini = 0), it means that all instances belong to a single class. For example, depth 1, left node.

##### Gini Impurity and Entropy

In a decision tree, by default `gini_impurity` is used. But, we can use `entropy` by changing the `criterion` hyperparameter to "`entropy`". The Gini impurity is one of the methods used in decision tree algorithms to decide the optimal split from a root node and subsequent splits.

The entropy concept came from thermodynamics, where if entropy approaches 0, it means that the molecules are still and well-ordered. In ML, it is used to measure impurity: a set's entropy of 0 means that all the instances belong to the same class.

*Equation for calculating the Gini-impurity:*

$G_i = 1 - \sum_{k=1}^{n} p_{i,k}^2$

The above equation shows how the training algorithm computes the Gini-score $G_i$ of the $i^{th}$ node.

For example, the *depth-2 left node* has a Gini score equal to $1 – (0/54)^2 – (49/54)^2 – (5/54)^2 \approx 0.168$.

*Equation for calculating the Entropy:*

$H_i = - \sum_{k=1}^{n} p_{i,k} \log_2 (p_{i,k})$, $\hspace{0.5cm}where, p_{i,k} \neq 0$

The above equation shows the definition of the entropy of the $i^{th}$ node.

For example, given above, the *depth-2 left node* has an entropy equal to $- \frac{49}{54} \log_2 (\frac{49}{54}) - \frac{5}{54} \log_2 (\frac{5}{54}) \approx 0.445$

Where, $k$ is the class of the problem. In this example, there are three classes: Iris-Versicolor, Iris-Setosa, and Iris-Virginica.

#### Estimating Class Probabilities

The instance probability denoted by $p_{i,k}$ denotes the probability that an instance belongs to class $k$.

For example, we have a flower whose sepal length is 5cm and sepal width is 1.5cm (depth 2, left node). The following probabilities: 0% for Iris-Setosa $(\frac{0}{54})$, 90.74% for Iris-Versicolor $(\frac{49}{54})$, and 9.25% for Iris-Virginica $(\frac{5}{54})$. And this will predict the class as Iris-Versicolor.
"""

